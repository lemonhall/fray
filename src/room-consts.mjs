/**
 * Room 的三个时间/频率常量。
 *
 * 单独放一个文件，是因为 `room.mjs`（对局生命周期）与 `room-conns.mjs`（连接面）
 * 各需要其中一个；谁都不该去 import 另一个的私有常量，那会把两件事重新粘起来。
 */

/** 广播节流窗口：**目标**是 20Hz 往外发快照（见 `room.mjs` 的 `tick`）。 */
export const BROADCAST_MS = 50;

/** 单连接每秒最多接受多少条上行消息，超了整条丢掉（不做排队，也不踢人）。 */
export const MAX_MSGS_PER_SEC = 70;

/** alarm 兜底间隔：清空房、续房间目录，以及"输入流断了也别让世界停死"。 */
export const ALARM_MS = 5000;

/**
 * 一个房间怎么样才算"死了"：**连接全断**，或者连着却连一条消息都不来。
 *
 * 注意这里**不**看名册有没有动过。名册在对局当中本来就不动（没人进、没人选边），
 * 拿它当判据的后果是"打到一半的房间被回收、名册连带被清空"——一个纯粹的破坏性
 * 行为，只换来省下几个空房间的内存。
 */
export const ROOM_IDLE_MS = 30 * 60_000;

/** 活跃房间往目录回写的节流窗口：对局中名册不动，不补写就会被目录当成过期房间删掉。 */
export const ROOM_PUBLISH_MS = 30_000;
