/**
 * 客户端那一半：**从权威确认点重放还没被确认的命令**。
 *
 * 这是整个手感问题的根治手段，值得写清楚它为什么比"比一比再拉回来"强：
 *
 * 老做法是拿最新快照里的权威坐标和本机预测坐标相减，差距大了就拽——问题是那个
 * 权威坐标是**过去的**（延迟 + 节流），而且"过去多久"一直在变。于是每一次对账
 * 都在往回调一点点，网络一抖就叠成一次硬吸附，眼睛看到的就是"往前走了一小段，
 * 又被拽回去"。
 *
 * 新做法不比较"现在的两个位置"，而是回到时间线上：服务端告诉我"第 42 条命令
 * 已经走完，那时你在 (x, y)"，那我就从 (x, y) 出发，把 43 条以后的命令逐格重放。
 * 只要两端用的是同一个 `applyMove`（本项目正是如此），重放结果就和本机预测**逐
 * 像素相同**——正常情况下这次对账的位移改动量是 0，画面上什么都不发生。
 *
 * 只有当服务端真的干了客户端没算到的事（闪避、被击退、破墙、草丛外的箱子被打碎），
 * 重放结果才会和本机位置不一样——那才是"该纠正的分歧"。
 */

import { DT } from "./constants.mjs";
import { applyMove } from "./input.mjs";

/**
 * 把 `cmds`（按发出顺序、每条带格数）从 `(x, y)` 开始逐格重放。
 * 只动位移，不动角度/开火/弹药——那些不属于"位置对账"的范畴。
 */
export function replayFrom(w, a, cmds, x, y) {
  a.x = x;
  a.y = y;
  for (const cmd of cmds) {
    for (let i = 0; i < cmd.n; i++) applyMove(w, a, cmd.mx, cmd.my, DT);
  }
  return a;
}

/** 待确认命令的总格数：理论上应当一直约等于"链路单向延迟折成的格数"。 */
export const pendingTicks = cmds => cmds.reduce((sum, cmd) => sum + (cmd.n | 0), 0);
